DROP TABLE IF EXISTS sessions;
DROP TABLE IF EXISTS user_roles;
DROP TABLE IF EXISTS roles;
DROP TABLE IF EXISTS users;

DROP TABLE IF EXISTS promotion_required_products;
DROP TABLE IF EXISTS promotion_target_products;
DROP TABLE IF EXISTS promotions;

DROP TABLE IF EXISTS order_items;
DROP TABLE IF EXISTS orders;
DROP TABLE IF EXISTS products;


-- =========================================================
-- SECURITY / USERS
-- =========================================================

CREATE TABLE users (
                       id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                       username VARCHAR(255) NOT NULL,
                       password VARCHAR(255) NOT NULL,
                       name VARCHAR(255) NOT NULL,

                       CONSTRAINT uq_users_username
                           UNIQUE (username)
);


CREATE TABLE roles (
                       id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                       name VARCHAR(50) NOT NULL,

                       CONSTRAINT uq_roles_name
                           UNIQUE (name)
);


CREATE TABLE user_roles (
                            user_id BIGINT NOT NULL,
                            role_id BIGINT NOT NULL,

                            CONSTRAINT pk_user_roles
                                PRIMARY KEY (user_id, role_id),

                            CONSTRAINT fk_user_roles_user
                                FOREIGN KEY (user_id)
                                    REFERENCES users(id),

                            CONSTRAINT fk_user_roles_role
                                FOREIGN KEY (role_id)
                                    REFERENCES roles(id)
);


INSERT INTO roles (name)
VALUES
    ('ADMIN'),
    ('EMPLOYEE'),
    ('USER');


-- =========================================================
-- PRODUCTS
-- =========================================================

CREATE TABLE products (
                          id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                          name VARCHAR(255) NOT NULL,
                          product_status VARCHAR(50) NOT NULL,
                          product_version BIGINT NOT NULL DEFAULT 1
);


-- =========================================================
-- ORDERS
-- =========================================================

CREATE TABLE orders (
                        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        status VARCHAR(50) NOT NULL,
                        created_at TIMESTAMP NOT NULL
);


CREATE TABLE order_items (
                             id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                             order_id BIGINT NOT NULL,
                             product_id BIGINT NOT NULL,
                             product_name VARCHAR(255) NOT NULL,

                             CONSTRAINT fk_order_items_order
                                 FOREIGN KEY (order_id)
                                     REFERENCES orders(id),

                             CONSTRAINT fk_order_items_product
                                 FOREIGN KEY (product_id)
                                     REFERENCES products(id)
);


-- =========================================================
-- PROMOTIONS
-- =========================================================

CREATE TABLE promotions (
                            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                            created_at TIMESTAMP NOT NULL,

                            start_date TIMESTAMP NOT NULL,
                            end_date TIMESTAMP NOT NULL,

                            status VARCHAR(50) NOT NULL,
                            promotion_type VARCHAR(50) NOT NULL,

                            occurrences INT,
                            minimum_value DECIMAL(19,4),

                            reward_type VARCHAR(50) NOT NULL,
                            reward_value DECIMAL(19,4)
);


CREATE TABLE promotion_target_products (
                                           promotion_id BIGINT NOT NULL,
                                           product_id BIGINT NOT NULL,

                                           CONSTRAINT pk_promotion_target_products
                                               PRIMARY KEY (promotion_id, product_id),

                                           CONSTRAINT fk_promotion_target_products_promotion
                                               FOREIGN KEY (promotion_id)
                                                   REFERENCES promotions(id),

                                           CONSTRAINT fk_promotion_target_products_product
                                               FOREIGN KEY (product_id)
                                                   REFERENCES products(id)
);


CREATE TABLE promotion_required_products (
                                             promotion_id BIGINT NOT NULL,
                                             product_id BIGINT NOT NULL,

                                             CONSTRAINT pk_promotion_required_products
                                                 PRIMARY KEY (promotion_id, product_id),

                                             CONSTRAINT fk_promotion_required_products_promotion
                                                 FOREIGN KEY (promotion_id)
                                                     REFERENCES promotions(id),

                                             CONSTRAINT fk_promotion_required_products_product
                                                 FOREIGN KEY (product_id)
                                                     REFERENCES products(id)
);

CREATE TABLE sessions (
                          id VARCHAR(255) PRIMARY KEY,
                          user_id BIGINT NOT NULL,
                          expires_at TIMESTAMP NOT NULL,

                          CONSTRAINT fk_sessions_user
                              FOREIGN KEY (user_id)
                                  REFERENCES users(id)
);